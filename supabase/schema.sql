-- DD CHAT database setup
-- Run in Supabase SQL Editor. Safe to re-run for the standard tables/policies below.

create table if not exists public.chat_room_members (
  room text not null,
  user_id uuid not null references auth.users(id) on delete cascade,
  joined_at timestamptz not null default now(),
  primary key (room, user_id)
);

create table if not exists public.chat_messages (
  id bigint generated by default as identity primary key,
  room text not null default 'The Group Chat',
  user_id uuid not null references auth.users(id) on delete cascade,
  username text not null,
  content text not null check (char_length(content) between 1 and 4000),
  created_at timestamptz not null default now()
);

alter table public.chat_room_members enable row level security;
alter table public.chat_messages enable row level security;

create or replace function public.is_chat_room_member(
  room_name text,
  member_id uuid
)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.chat_room_members m
    where m.room = room_name
      and m.user_id = member_id
  );
$$;

revoke all on function public.is_chat_room_member(text, uuid) from public;
grant execute on function public.is_chat_room_member(text, uuid) to authenticated;

drop policy if exists "Signed-in users can read chat messages" on public.chat_messages;
drop policy if exists "Users can send as themselves" on public.chat_messages;
drop policy if exists "Members can read room messages" on public.chat_messages;
drop policy if exists "Members can send their own messages" on public.chat_messages;

create policy "Members can read room messages"
  on public.chat_messages for select to authenticated
  using (public.is_chat_room_member(room, auth.uid()));

create policy "Members can send their own messages"
  on public.chat_messages for insert to authenticated
  with check (
    auth.uid() = user_id
    and public.is_chat_room_member(room, auth.uid())
  );

drop policy if exists "Members can view their room memberships" on public.chat_room_members;
create policy "Members can view their room memberships"
  on public.chat_room_members for select to authenticated
  using (user_id = auth.uid());

grant select on public.chat_room_members to authenticated;
grant select, insert on public.chat_messages to authenticated;
grant usage, select on sequence public.chat_messages_id_seq to authenticated;

-- Existing accounts enter the default circle only.
insert into public.chat_room_members (room, user_id)
select 'The Group Chat', id from auth.users
on conflict (room, user_id) do nothing;

create or replace function public.add_new_user_to_default_chat()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.chat_room_members (room, user_id)
  values ('The Group Chat', new.id)
  on conflict (room, user_id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created_add_default_chat on auth.users;
create trigger on_auth_user_created_add_default_chat
after insert on auth.users
for each row execute function public.add_new_user_to_default_chat();

alter table public.chat_messages replica identity full;

do $$
begin
  alter publication supabase_realtime add table public.chat_messages;
exception
  when duplicate_object then null;
  when undefined_object then null;
end $$;
